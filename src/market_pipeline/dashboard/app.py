"""Streamlit dashboard for Market Data Pipeline.

Launch with ``mdp dashboard``. It reads the database named by ``MDP_DB_PATH``
(or the default path) and never contacts external services.
"""

from __future__ import annotations

from datetime import date
from typing import Any

import plotly.graph_objects as go
import streamlit as st
from plotly.subplots import make_subplots

from market_pipeline.config import default_db_path, sample_data_dir
from market_pipeline.pipeline import run_pipeline
from market_pipeline.reporting import coverage_report
from market_pipeline.sources.csv_source import CsvSource
from market_pipeline.storage import Database

SYNTHETIC_NOTICE = (
    "All bundled data is **synthetic**: generated by a seeded random-walk script. "
    "It does not describe any real company, security or market."
)

#: Short labels that fit in a metric tile; the raw status is shown in its tooltip.
STATUS_LABELS = {"success": "Success", "partial_success": "Partial", "failed": "Failed"}


def main() -> None:
    st.set_page_config(page_title="Market Data Pipeline", layout="wide")
    st.title("Market Data Pipeline")
    db_path = default_db_path()
    # Only the file name is shown, so screenshots never include local paths.
    st.caption(f"SQLite database: `{db_path.name}`")
    st.info(SYNTHETIC_NOTICE)

    with Database(db_path) as db:
        db.init_schema()
        overview = db.overview()
        if overview["price_rows"] == 0:
            render_empty_state(db)
            return
        render_overview(overview)
        prices_tab, coverage_tab, runs_tab = st.tabs(["Prices", "Data coverage", "Pipeline runs"])
        with prices_tab:
            render_prices(db)
        with coverage_tab:
            render_coverage(db)
        with runs_tab:
            render_runs(db)


def render_empty_state(db: Database) -> None:
    st.warning("The database has no price data yet.")
    st.write("Load the bundled synthetic dataset, or run `mdp run` in a terminal.")
    if st.button("Load synthetic sample data", type="primary"):
        summary = run_pipeline(db, CsvSource(sample_data_dir("base")))
        st.success(
            f"Run #{summary.run_id} finished with status {summary.status}: "
            f"{summary.counters.rows_inserted} rows inserted."
        )
        st.rerun()


def render_overview(overview: dict[str, Any]) -> None:
    last_run = overview["last_run"]
    columns = st.columns(4)
    columns[0].metric("Securities", overview["securities"])
    columns[1].metric("Daily price rows", f"{overview['price_rows']:,}")
    columns[2].metric(
        "Latest trade date",
        overview["last_date"],
        help=f"Data starts {overview['first_date']}",
    )
    columns[3].metric(
        "Last pipeline run",
        STATUS_LABELS.get(last_run["status"], last_run["status"]) if last_run else "None",
        help=(
            f"Run #{last_run['id']} ({last_run['status']}) started {last_run['started_at']} UTC"
            if last_run
            else None
        ),
    )
    st.caption(
        f"Stored history: {overview['first_date']} to {overview['last_date']} - "
        f"{overview['runs']} pipeline run(s) logged."
    )


def render_prices(db: Database) -> None:
    securities = db.list_securities()
    labels = {s["symbol"]: f"{s['symbol']} - {s['name']}" for s in securities}
    coverage = {row["symbol"]: row for row in db.coverage()}
    with_data = [symbol for symbol in labels if coverage[symbol]["rows"]]

    symbol = st.selectbox("Security", with_data, format_func=lambda s: labels[s])
    if symbol is None:
        return
    first = date.fromisoformat(coverage[symbol]["first_date"])
    last = date.fromisoformat(coverage[symbol]["last_date"])
    picked = st.date_input("Date range", value=(first, last), min_value=first, max_value=last)
    start, end = picked if isinstance(picked, tuple) and len(picked) == 2 else (first, last)

    rows = db.price_history(symbol, start, end)
    if not rows:
        st.write("No prices in the selected range.")
        return

    first_close, last_close = rows[0]["close"], rows[-1]["close"]
    stats = st.columns(4)
    stats[0].metric("Last close", f"{last_close:,.2f}")
    stats[1].metric("Change over range", f"{100 * (last_close / first_close - 1):+.2f}%")
    stats[2].metric("Range high", f"{max(r['high'] for r in rows):,.2f}")
    stats[3].metric("Range low", f"{min(r['low'] for r in rows):,.2f}")

    dates = [r["trade_date"] for r in rows]
    figure = make_subplots(
        rows=2, cols=1, shared_xaxes=True, row_heights=[0.75, 0.25], vertical_spacing=0.04
    )
    figure.add_trace(
        go.Candlestick(
            x=dates,
            open=[r["open"] for r in rows],
            high=[r["high"] for r in rows],
            low=[r["low"] for r in rows],
            close=[r["close"] for r in rows],
            name="OHLC",
        ),
        row=1,
        col=1,
    )
    figure.add_trace(
        go.Bar(x=dates, y=[r["volume"] for r in rows], name="Volume", marker_color="#8c9bab"),
        row=2,
        col=1,
    )
    figure.update_layout(
        height=520,
        showlegend=False,
        xaxis_rangeslider_visible=False,
        margin={"l": 10, "r": 10, "t": 30, "b": 10},
        title=labels[symbol],
    )
    st.plotly_chart(figure)


def render_coverage(db: Database) -> None:
    st.dataframe(coverage_report(db), hide_index=True)
    st.caption(
        "Expected weekdays count Monday-Friday between the first and last stored date. "
        "Exchange holidays are not modelled."
    )


def render_runs(db: Database) -> None:
    runs = db.list_runs(limit=50)
    columns = [
        "id",
        "started_at",
        "finished_at",
        "status",
        "mode",
        "symbols_planned",
        "symbols_failed",
        "rows_read",
        "rows_inserted",
        "rows_updated",
        "rows_unchanged",
        "rows_skipped",
        "rows_rejected",
        "error_message",
    ]
    st.dataframe([{name: run[name] for name in columns} for run in runs], hide_index=True)

    run_id = st.selectbox("Show recorded problems for run", [run["id"] for run in runs])
    if run_id is not None:
        errors = db.run_errors(run_id)
        if errors:
            st.dataframe(errors, hide_index=True)
        else:
            st.write("No problems recorded for this run.")


main()
